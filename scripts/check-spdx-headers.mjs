// SPDX header gate for selbstbehalt.
//
// Apache-2.0 — unlike MIT — keeps the copyright notice *out* of the license
// text: § 4(c) obliges redistributors to preserve the notices found in the
// original, and the APPENDIX of `LICENSE` is only a template for file headers.
// So every first-party file states both halves itself:
//
//   SPDX-FileCopyrightText: <year> <holder>   ← whose work
//   SPDX-License-Identifier: Apache-2.0       ← under which license
//
// This script verifies that pair, adjacent and in that order, near the top of
// every first-party file. `--fix` inserts what is missing.
//
// Deliberately *not* covered (see EXCLUDES for the per-entry reasons): vendored
// third-party code, generated artifacts, official legal texts and files whose
// format cannot carry a comment. Asserting our copyright over those would be a
// false claim — the opposite of what this gate is for. Full REUSE conformance
// is therefore not a goal; that would need a `REUSE.toml` for the JSON and
// binary files.
//
// Run: `pnpm headers:check` (or `node scripts/check-spdx-headers.mjs [--fix]`).
// Plain Node, no external packages — the CI job runs it without `pnpm install`.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const COPYRIGHT_HOLDER = '2026 Bastian Rang and contributors';
const LICENSE_ID = 'Apache-2.0';

// How many leading lines may precede the header. Some files must open with
// something else (shebang, `# syntax=` directive, doctype, `/// <reference>`),
// so the pair is allowed to start a little further down.
const MAX_HEADER_OFFSET = 8;

// Comment syntax per file type. `line` wraps each line with a prefix; `wrap`
// encloses each line in an open/close pair.
const LINE_COMMENT = (prefix) => ({ kind: 'line', prefix });
const WRAP_COMMENT = (open, close) => ({ kind: 'wrap', open, close });

const SLASH = LINE_COMMENT('//');
const HASH = LINE_COMMENT('#');
const MARKUP = WRAP_COMMENT('<!--', '-->');
const BLOCK = WRAP_COMMENT('/*', '*/');

// Extension → comment style. A file type absent here is not checked at all;
// that is how JSON, lockfiles and binaries stay out without needing an exclude.
const STYLE_BY_EXTENSION = new Map([
  ['ts', SLASH],
  ['mts', SLASH],
  ['cts', SLASH],
  ['js', SLASH],
  ['mjs', SLASH],
  ['cjs', SLASH],
  ['svelte', MARKUP],
  ['html', MARKUP],
  ['md', MARKUP],
  ['svg', MARKUP],
  ['css', BLOCK],
  ['yml', HASH],
  ['yaml', HASH],
  ['sh', HASH],
  ['sql', HASH],
  ['conf', HASH],
  ['example', HASH],
  ['txt', HASH],
  ['dockerignore', HASH],
  ['prettierignore', HASH],
  ['gitignore', HASH],
  ['editorconfig', HASH],
]);

// Extensionless files that still carry a header, keyed by basename.
const STYLE_BY_BASENAME = new Map([
  ['Dockerfile', HASH],
  ['Caddyfile', HASH],
  ['CODEOWNERS', HASH],
  ['pre-commit', HASH],
  ['commit-msg', HASH],
]);

// Paths excluded from the gate. Globs support `*` (within one segment) and `**`.
// Every entry states why — an exclude without a reason is a bug.
const EXCLUDES = [
  // shadcn-svelte components, added and overwritten by the shadcn CLI
  // (`components.json` points `ui` here). Third-party work under its own (MIT)
  // license — including the locally renamed and trimmed variants, which are
  // derivatives of it, not original work.
  '**/src/lib/components/ui/**',
  // Vendored agent skill pulled from the shadcn/ui repository (skills-lock.json).
  '.agents/**',
  '.claude/**',
  // Generated by drizzle-kit — a header would be dropped on regeneration.
  'apps/backend/src/db/migrations/**',
  // Generated by `pnpm fees:build`; CI checks these for byte-reproducibility.
  'packages/medic-invoice-check/src/lib/data/goae.json',
  'packages/medic-invoice-check/src/lib/data/goz.json',
  'packages/medic-invoice-check/src/lib/data/got.json',
  // Official legal texts from gesetze-im-internet.de (amtliche Werke, § 5 UrhG)
  // — build inputs, not our work.
  'data/input/**',
  // Generated by release-please on every release.
  'CHANGELOG.md',
  // Generated by pnpm; rewritten wholesale on every resolution change.
  'pnpm-lock.yaml',
  // Must remain the verbatim canonical Apache-2.0 text.
  'LICENSE',
  // Checksum manifests consumed byte-for-byte by `pnpm ocr:models`.
  '**/models.sha256',
  // `nvm` reads the whole file as a version string; a comment breaks it.
  '.nvmrc',
  // Must stay empty to serve its purpose.
  'packages/.gitkeep',
];

// Files that sit under an excluded path but are first-party nonetheless. Empty
// by design: everything under `components/ui/**` traces back to shadcn-svelte.
const ALLOWLIST = new Set([]);

/** Translate a glob (`*`, `**`) into an anchored regex. */
function globToRegExp(glob) {
  let out = '^';
  for (let i = 0; i < glob.length; i += 1) {
    const char = glob[i];
    if (char === '*') {
      if (glob[i + 1] === '*') {
        // `**/` may also match zero segments, so `a/**/b` matches `a/b`.
        if (glob[i + 2] === '/') {
          out += '(?:.*/)?';
          i += 2;
        } else {
          out += '.*';
          i += 1;
        }
      } else {
        out += '[^/]*';
      }
    } else {
      out += char.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
    }
  }
  return new RegExp(`${out}$`);
}

const EXCLUDE_PATTERNS = EXCLUDES.map(globToRegExp);

function isExcluded(path) {
  if (ALLOWLIST.has(path)) return false;
  return EXCLUDE_PATTERNS.some((pattern) => pattern.test(path));
}

/** The comment style for a path, or null if the file type is not checked. */
function styleFor(path) {
  const basename = path.slice(path.lastIndexOf('/') + 1);
  const byBasename = STYLE_BY_BASENAME.get(basename);
  if (byBasename) return byBasename;

  // A leading dot is part of the name, not an extension separator: `.gitignore`
  // is keyed as `gitignore`, while `foo.bar.ts` resolves to `ts`.
  const dot = basename.lastIndexOf('.');
  if (dot <= 0) return STYLE_BY_EXTENSION.get(basename.slice(1)) ?? null;
  return STYLE_BY_EXTENSION.get(basename.slice(dot + 1)) ?? null;
}

// Markdown needs a blank line between the header block and the following
// block, otherwise Prettier folds them together and `format:check` fails.
function needsBlankLineAfterHeader(path) {
  return path.endsWith('.md');
}

function renderComment(style, text) {
  return style.kind === 'line' ? `${style.prefix} ${text}` : `${style.open} ${text} ${style.close}`;
}

function commentBodyPattern(style, body) {
  const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return style.kind === 'line'
    ? new RegExp(`^\\s*${escape(style.prefix)}\\s*${body}\\s*$`)
    : new RegExp(`^\\s*${escape(style.open)}\\s*${body}\\s*${escape(style.close)}\\s*$`);
}

/**
 * First line index at which a header may legally be inserted: after a shebang,
 * a Dockerfile parser directive, an XML declaration (a comment above it would
 * be invalid XML), a doctype or a run of triple-slash references.
 */
function insertionIndex(lines) {
  let index = 0;
  if (/^#!/.test(lines[0] ?? '')) index = 1;
  else if (/^#\s*syntax=/.test(lines[0] ?? '')) index = 1;
  else if (/^<\?xml\b/.test(lines[0] ?? '')) index = 1;
  else if (/^<!doctype/i.test(lines[0] ?? '')) index = 1;
  while (/^\/\/\/\s*<reference\b/.test(lines[index] ?? '')) index += 1;
  return index;
}

/**
 * Inspect one file. Returns `{ ok }`, or the pieces needed to fix it:
 * `insertAt` and whether an identifier line is already present.
 */
function inspect(path, style) {
  const lines = readFileSync(path, 'utf8').split('\n');
  const head = lines.slice(0, MAX_HEADER_OFFSET);
  const copyright = commentBodyPattern(style, 'SPDX-FileCopyrightText:\\s*\\S.*');
  const identifier = commentBodyPattern(style, `SPDX-License-Identifier:\\s*${LICENSE_ID}`);

  const identifierAt = head.findIndex((line) => identifier.test(line));
  const pairFound = head.some(
    (line, i) => copyright.test(line) && identifier.test(head[i + 1] ?? ''),
  );
  if (pairFound) return { ok: true };

  return {
    ok: false,
    lines,
    // With an identifier already in place the copyright line goes directly
    // above it; otherwise the whole pair goes to the first legal position.
    insertAt: identifierAt >= 0 ? identifierAt : insertionIndex(lines),
    hasIdentifier: identifierAt >= 0,
    reason: identifierAt >= 0 ? 'missing SPDX-FileCopyrightText' : 'missing SPDX header',
  };
}

function fix(path, style, result) {
  const addition = [renderComment(style, `SPDX-FileCopyrightText: ${COPYRIGHT_HOLDER}`)];
  if (!result.hasIdentifier) {
    addition.push(renderComment(style, `SPDX-License-Identifier: ${LICENSE_ID}`));
  }
  const lines = [...result.lines];
  const following = lines[result.insertAt] ?? '';
  if (needsBlankLineAfterHeader(path) && following.trim() !== '') addition.push('');
  lines.splice(result.insertAt, 0, ...addition);
  writeFileSync(path, lines.join('\n'));
}

function trackedFiles() {
  // `-s` exposes the mode so symlinks (120000) can be skipped: they have no
  // content of their own to annotate.
  return execFileSync('git', ['ls-files', '-s', '-z'], { encoding: 'utf8', maxBuffer: 32 << 20 })
    .split('\0')
    .filter(Boolean)
    .map((entry) => {
      const [meta, path] = entry.split('\t');
      return { mode: meta.split(' ')[0], path };
    })
    .filter(({ mode }) => mode !== '120000');
}

function main() {
  const shouldFix = process.argv.includes('--fix');
  const violations = [];
  let checked = 0;
  let fixed = 0;

  for (const { path } of trackedFiles()) {
    if (isExcluded(path)) continue;
    const style = styleFor(path);
    if (!style) continue;

    checked += 1;
    const result = inspect(path, style);
    if (result.ok) continue;

    if (shouldFix) {
      fix(path, style, result);
      fixed += 1;
    } else {
      violations.push(`${path} — ${result.reason}`);
    }
  }

  if (shouldFix) {
    console.log(`Checked ${checked} files, fixed ${fixed}.`);
    return;
  }

  if (violations.length > 0) {
    console.error(`Missing or malformed SPDX header in ${violations.length} file(s):\n`);
    for (const violation of violations) console.error(`  ${violation}`);
    console.error(
      `\nEvery first-party file needs both lines, adjacent and in this order:\n` +
        `  SPDX-FileCopyrightText: ${COPYRIGHT_HOLDER}\n` +
        `  SPDX-License-Identifier: ${LICENSE_ID}\n` +
        `Run \`pnpm headers:check --fix\` to insert them, or add a documented\n` +
        `entry to EXCLUDES in scripts/check-spdx-headers.mjs if the file is\n` +
        `vendored, generated or cannot carry a comment.`,
    );
    process.exit(1);
  }

  console.log(`All ${checked} first-party files carry the SPDX copyright + license header.`);
}

main();
